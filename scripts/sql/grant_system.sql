-- Cap quyen TOI THIEU cho tai khoan NT AUTHORITY\SYSTEM (Scheduled Task chay duoi tai khoan nay).
-- Khong cho sysadmin: chi sao luu CSDL $(DB), doc lich su sao luu trong msdb, va RESTORE VERIFYONLY
-- (can quyen CREATE DATABASE theo tai lieu SQL Server). Bien sqlcmd: DB
SET NOCOUNT ON;
IF SUSER_ID(N'NT AUTHORITY\SYSTEM') IS NULL
    CREATE LOGIN [NT AUTHORITY\SYSTEM] FROM WINDOWS;
GRANT CREATE ANY DATABASE TO [NT AUTHORITY\SYSTEM];
GO
USE [$(DB)];
IF USER_ID(N'NT AUTHORITY\SYSTEM') IS NULL
    CREATE USER [NT AUTHORITY\SYSTEM] FOR LOGIN [NT AUTHORITY\SYSTEM];
ALTER ROLE db_backupoperator ADD MEMBER [NT AUTHORITY\SYSTEM];
GO
USE msdb;
IF USER_ID(N'NT AUTHORITY\SYSTEM') IS NULL
    CREATE USER [NT AUTHORITY\SYSTEM] FOR LOGIN [NT AUTHORITY\SYSTEM];
ALTER ROLE db_datareader ADD MEMBER [NT AUTHORITY\SYSTEM];
GO
PRINT N'Da cap quyen sao luu $(DB) cho NT AUTHORITY\SYSTEM';
